#!/usr/bin/env python3
"""Builds archive-format.html and schemas/ from the spec in the placemoir-app repo.

The spec's source of truth is docs/ in placemoir-app, next to the code that reads the
format. Run this after changing it, then commit what it writes here:

    pip install markdown
    python3 tools/archive-format.py ../placemoir-app

The page reuses privacy.html's head, header and footer, so it changes with them.
"""
import html
import pathlib
import re
import shutil
import sys

import markdown

SITE = pathlib.Path(__file__).resolve().parent.parent
TITLE = "Archive format"
DESCRIPTION = ("The public format for Placemoir archives and library files: how to write a file "
               "Placemoir imports, with instructions for AI assistants and scripts.")


def main(app_repo: pathlib.Path) -> None:
    docs = app_repo / "docs"
    source = (docs / "archive-format.md").read_text(encoding="utf-8")

    # The H1 and the source note belong to the repo copy; the page has its own header.
    heading, _, body = source.partition("\n")
    version = re.search(r"version (\d+)", heading).group(1)
    body = re.sub(r"\nPublished at \*\*.*?\n", "\n", body)
    content = markdown.markdown(body, extensions=["tables", "fenced_code", "toc"],
                                extension_configs={"toc": {"permalink": False}})
    # Code blocks scroll sideways on phones; tables too, inside a wrapper.
    content = content.replace("<table>", '<div class="table-scroll"><table>').replace("</table>", "</table></div>")

    template = (SITE / "privacy.html").read_text(encoding="utf-8")
    head, _, rest = template.partition('<main id="main">')
    _, _, foot = rest.partition("</main>")
    head = (head
            .replace("<title>Privacy Policy · Placemoir</title>", f"<title>{TITLE} · Placemoir</title>")
            .replace('href="https://placemoir.app/privacy.html"', 'href="https://placemoir.app/archive-format.html"')
            .replace('content="Privacy Policy · Placemoir"', f'content="{TITLE} · Placemoir"'))
    head = re.sub(r'(<meta (?:name|property)="(?:og:)?description" content=")[^"]*"',
                  lambda m: m.group(1) + html.escape(DESCRIPTION) + '"', head)

    page = f'''{head}<main id="main">
        <!-- Generated by tools/archive-format.py from docs/archive-format.md in placemoir-app. Don't edit here. -->
        <div class="wrap">
            <header class="page-head">
                <p class="eyebrow moss">For developers and AI assistants</p>
                <h1>The Placemoir archive format</h1>
                <p class="meta">Version {version} · <a href="schemas/library-v1.json">JSON Schema</a> · <a href="schemas/example-library.json">Example</a></p>
            </header>
        </div>
        <div class="wrap page-body">
            <article class="prose spec">
{content}
            </article>
        </div>
    </main>{foot}'''
    (SITE / "archive-format.html").write_text(page, encoding="utf-8")

    schemas = SITE / "schemas"
    schemas.mkdir(exist_ok=True)
    shutil.copyfile(docs / "library-v1.schema.json", schemas / "library-v1.json")
    shutil.copyfile(docs / "example-library.json", schemas / "example-library.json")
    print("Wrote archive-format.html and schemas/")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(pathlib.Path(sys.argv[1]).resolve())
